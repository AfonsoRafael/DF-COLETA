create index if not exists idx_comentarios_resposta on public.comentarios (resposta_a);
create index if not exists idx_problemas_ponto   on public.problemas (ponto_coleta_id);
create index if not exists idx_problemas_status  on public.problemas (status);
create index if not exists idx_sugestoes_data    on public.sugestoes (data desc);

-- ---------------------------------------------------------------------------
-- 3. Gatilho de atualização automática de atualizado_em
-- ---------------------------------------------------------------------------

create or replace function public.tocar_atualizado_em()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists trg_pontos_atualizado_em on public.pontos_coleta;
create trigger trg_pontos_atualizado_em
  before update on public.pontos_coleta
  for each row execute function public.tocar_atualizado_em();

-- ---------------------------------------------------------------------------
-- 4. View com resíduos e horários agregados (usada pelo backend)
-- ---------------------------------------------------------------------------

create or replace view public.pontos_coleta_completo
with (security_invoker = true)
as
select
  p.id,
  p.nome,
  p.tipo,
  p.endereco,
  p.cidade,
  p.latitude,
  p.longitude,
  p.telefone,
  p.status,
  p.criado_em,
  p.atualizado_em,
  coalesce(
    (
      select jsonb_agg(
               jsonb_build_object(
                 'id', r.id,
                 'nome', r.nome,
                 'icone', r.icone,
                 'descricao', r.descricao
               )
               order by r.nome
             )
      from public.ponto_residuos pr
      join public.residuos r on r.id = pr.residuo_id
      where pr.ponto_id = p.id
    ),
    '[]'::jsonb
  ) as residuos,
  coalesce(
    (
      select jsonb_agg(
               jsonb_build_object(
                 'id', h.id,
                 'dia_semana', h.dia_semana,
                 'hora_abertura', to_char(h.hora_abertura, 'HH24:MI'),
                 'hora_fechamento', to_char(h.hora_fechamento, 'HH24:MI')
               )
               order by h.ordem, h.id
             )
      from public.horarios_funcionamento h
      where h.ponto_id = p.id
    ),
    '[]'::jsonb
  ) as horarios_funcionamento
from public.pontos_coleta p;

grant select on public.pontos_coleta_completo to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 5. RLS (Row Level Security)
--    O backend usa a chave service_role e ignora o RLS.
--    As políticas protegem o acesso direto com a chave anon.
-- ---------------------------------------------------------------------------

alter table public.residuos               enable row level security;
alter table public.pontos_coleta          enable row level security;
alter table public.ponto_residuos         enable row level security;
alter table public.horarios_funcionamento enable row level security;
alter table public.comentarios            enable row level security;
alter table public.problemas              enable row level security;
alter table public.sugestoes              enable row level security;

-- Resíduos: leitura pública, escrita apenas para administradores autenticados
drop policy if exists "residuos_leitura_publica" on public.residuos;
create policy "residuos_leitura_publica"
  on public.residuos for select
  to anon, authenticated
  using (true);

drop policy if exists "residuos_admin" on public.residuos;
create policy "residuos_admin"
  on public.residuos for all
  to authenticated
  using (true) with check (true);

-- Pontos: público vê apenas ativos; admin vê e gerencia tudo
drop policy if exists "pontos_leitura_ativos" on public.pontos_coleta;
create policy "pontos_leitura_ativos"
  on public.pontos_coleta for select
  to anon
  using (status = 'ATIVO');

drop policy if exists "pontos_admin" on public.pontos_coleta;
create policy "pontos_admin"
  on public.pontos_coleta for all
  to authenticated
  using (true) with check (true);

