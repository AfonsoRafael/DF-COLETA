-- ---------------------------------------------------------------------------
-- 1. Tabelas
-- ---------------------------------------------------------------------------

create table if not exists public.residuos (
  id         bigint generated by default as identity primary key,
  nome       text not null unique,
  icone      text,
  descricao  text,
  criado_em  timestamptz not null default now()
);

create table if not exists public.pontos_coleta (
  id            bigint generated by default as identity primary key,
  nome          text not null,
  tipo          text not null default 'ECOPONTO'
                check (tipo in ('ECOPONTO','COOPERATIVA','FARMACIA','COMERCIO','COMUNITARIO','ESCOLA')),
  endereco      text not null,
  cidade        text not null,
  latitude      double precision,
  longitude     double precision,
  telefone      text,
  status        text not null default 'ATIVO'
                check (status in ('ATIVO','INATIVO')),
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.ponto_residuos (
  ponto_id   bigint not null references public.pontos_coleta(id) on delete cascade,
  residuo_id bigint not null references public.residuos(id) on delete cascade,
  primary key (ponto_id, residuo_id)
);

create table if not exists public.horarios_funcionamento (
  id              bigint generated by default as identity primary key,
  ponto_id        bigint not null references public.pontos_coleta(id) on delete cascade,
  dia_semana      text not null,
  hora_abertura   time,
  hora_fechamento time,
  ordem           integer not null default 0
);

create table if not exists public.comentarios (
  id                bigint generated by default as identity primary key,
  ponto_coleta_id   bigint not null references public.pontos_coleta(id) on delete cascade,
  nome_autor        text not null,
  email_autor       text,
  texto_comentario  text not null,
  curtidas          integer not null default 0,
  resposta_a        bigint references public.comentarios(id) on delete cascade,
  oficial           boolean not null default false,
  data              timestamptz not null default now()
);

create table if not exists public.problemas (
  id               bigint generated by default as identity primary key,
  ponto_coleta_id  bigint references public.pontos_coleta(id) on delete cascade,
  nome_autor       text,
  email_autor      text,
  tipo_problema    text,
  severidade       text not null default 'MEDIA'
                   check (severidade in ('BAIXA','MEDIA','ALTA')),
  texto_problema   text not null,
  status           text not null default 'PENDENTE'
                   check (status in ('PENDENTE','EM_ANALISE','RESOLVIDO')),
  data             timestamptz not null default now()
);

create table if not exists public.sugestoes (
  id                  bigint generated by default as identity primary key,
  nome_local          text,
  endereco            text,
  cidade              text,
  nome_autor          text,
  email_autor         text,
  texto_sugestao      text,
  residuos_sugeridos  text,
  status              text not null default 'PENDENTE'
                      check (status in ('PENDENTE','APROVADO','REJEITADO')),
  data                timestamptz not null default now()
);

